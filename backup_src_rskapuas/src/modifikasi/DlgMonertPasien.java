public void tampil() {
    Valid.tabelKosong(tabMode);

    StringBuilder sql = new StringBuilder();

    sql.append("SELECT ")
       .append("m.no_rawat, ")
       .append("m.no_rkm_medis, ")
       .append("m.nama_pasien, ")
       .append("DATE(m.date_time) AS tgl_perawatan, ")
       .append("TIME(m.date_time) AS jam_rawat, ")
       .append("CONCAT(COALESCE(b.nm_bangsal,''), ")
       .append("' / ', COALESCE(ki.kd_kamar,'')) AS nama_bangsal, ")

       .append("MAX(CASE WHEN m.test_name='temp' ")
       .append("THEN m.nilai END) AS suhu_tubuh, ")

       .append("CASE ")
       .append("WHEN MAX(CASE WHEN m.test_name='nibp_sys' ")
       .append("THEN m.nilai END) IS NOT NULL ")
       .append("AND MAX(CASE WHEN m.test_name='nibp_dia' ")
       .append("THEN m.nilai END) IS NOT NULL ")
       .append("THEN CONCAT(")
       .append("MAX(CASE WHEN m.test_name='nibp_sys' ")
       .append("THEN m.nilai END), '/', ")
       .append("MAX(CASE WHEN m.test_name='nibp_dia' ")
       .append("THEN m.nilai END)) ")
       .append("ELSE NULL END AS tensi, ")

       .append("MAX(CASE WHEN m.test_name='hr' ")
       .append("THEN m.nilai END) AS nadi, ")

       .append("MAX(CASE WHEN m.test_name='resp' ")
       .append("THEN m.nilai END) AS respirasi, ")

       .append("MAX(CASE WHEN m.test_name='spo2' ")
       .append("THEN m.nilai END) AS spo2, ")

       .append("MIN(m.id) AS id ")

       .append("FROM monert_tanda_vital m ")

       .append("LEFT JOIN kamar_inap ki ")
       .append("ON ki.no_rawat=m.no_rawat ")
       .append("AND (ki.tgl_keluar IS NULL ")
       .append("OR ki.tgl_keluar='0000-00-00') ")

       .append("LEFT JOIN kamar k ON k.kd_kamar=ki.kd_kamar ")
       .append("LEFT JOIN bangsal b ON b.kd_bangsal=k.kd_bangsal ")

       .append("WHERE m.nama_grup='data_vital_sign' ")
       .append("AND m.date_time BETWEEN ? AND ? ");

    boolean cari = !TCari.getText().trim().isEmpty();

    if (cari) {
        sql.append("AND (")
           .append("m.no_rawat LIKE ? ")
           .append("OR m.no_rkm_medis LIKE ? ")
           .append("OR m.nama_pasien LIKE ? ")
           .append("OR b.nm_bangsal LIKE ? ")
           .append("OR ki.kd_kamar LIKE ? ")
           .append(") ");
    }

    sql.append("GROUP BY ")
       .append("m.no_rawat, ")
       .append("m.no_rkm_medis, ")
       .append("m.nama_pasien, ")
       .append("DATE(m.date_time), ")
       .append("TIME(m.date_time), ")
       .append("b.nm_bangsal, ")
       .append("ki.kd_kamar ")

       .append("ORDER BY tgl_perawatan DESC, jam_rawat DESC");

    try (PreparedStatement ps = koneksi.prepareStatement(sql.toString())) {

        int parameter = 1;

        ps.setString(parameter++,
            Valid.SetTgl(Tgl1.getSelectedItem() + "") + " 00:00:00");

        ps.setString(parameter++,
            Valid.SetTgl(Tgl2.getSelectedItem() + "") + " 23:59:59");

        if (cari) {
            String keyword = "%" + TCari.getText().trim() + "%";

            ps.setString(parameter++, keyword);
            ps.setString(parameter++, keyword);
            ps.setString(parameter++, keyword);
            ps.setString(parameter++, keyword);
            ps.setString(parameter++, keyword);
        }

        try (ResultSet rs = ps.executeQuery()) {
            while (rs.next()) {
                tabMode.addRow(new Object[]{
                    rs.getString("no_rawat"),
                    rs.getString("no_rkm_medis"),
                    rs.getString("nama_pasien"),
                    rs.getString("tgl_perawatan") + " "
                        + rs.getString("jam_rawat"),
                    rs.getString("nama_bangsal"),
                    rs.getString("suhu_tubuh"),
                    rs.getString("tensi"),
                    rs.getString("nadi"),
                    rs.getString("respirasi"),
                    rs.getString("spo2"),
                    rs.getString("id")
                });
            }
        }

    } catch (Exception e) {
        System.out.println("Gagal menampilkan data MONERT: " + e.getMessage());
    }

    LCount.setText("" + tabMode.getRowCount());
}

     
